CREATE POLICY tickets_select ON tickets FOR SELECT USING (aluno_id = auth.uid() OR public.ticket_visible(queue_id, atendente_id));
CREATE POLICY tickets_update ON tickets FOR UPDATE USING (aluno_id = auth.uid() OR public.ticket_visible(queue_id, atendente_id));

