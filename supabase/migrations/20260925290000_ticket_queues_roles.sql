-- ── roteamento ──────────────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.ticket_route(p_categoria ticket_categoria, p_nivel text) RETURNS bigint
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT id FROM (
    SELECT id, 0 AS prio, ordem FROM ticket_queues
     WHERE ativo AND p_categoria = ANY(categorias) AND nivel = p_nivel
    UNION ALL
    SELECT id, 1, ordem FROM ticket_queues
     WHERE ativo AND p_categoria = ANY(categorias) AND nivel = 'todos'
    UNION ALL
    SELECT id, 2, ordem FROM ticket_queues WHERE ativo AND padrao
  ) q ORDER BY prio, ordem LIMIT 1;
$$;

CREATE OR REPLACE FUNCTION public.ticket_set_queue() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF NEW.nivel IS NULL THEN
    SELECT CASE WHEN c.type ILIKE 'p%s%' THEN 'pos' WHEN c.type ILIKE 'gradua%' THEN 'graduacao' END
      INTO NEW.nivel FROM courses c WHERE c.id = NEW.curso_id;
    IF NEW.nivel IS NULL AND NEW.aluno_id IS NOT NULL THEN
      SELECT nivel INTO NEW.nivel FROM alunos WHERE id = NEW.aluno_id;
    END IF;
  END IF;
  IF NEW.queue_id IS NULL OR (TG_OP = 'UPDATE' AND NEW.categoria IS DISTINCT FROM OLD.categoria AND NEW.queue_id IS NOT DISTINCT FROM OLD.queue_id) THEN
    NEW.queue_id := public.ticket_route(NEW.categoria, NEW.nivel);
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_ticket_set_queue ON tickets;
CREATE TRIGGER trg_ticket_set_queue BEFORE INSERT OR UPDATE OF categoria ON tickets
  FOR EACH ROW EXECUTE FUNCTION public.ticket_set_queue();

