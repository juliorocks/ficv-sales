-- ============================================================================
-- Atendimento do aluno: funções + filas (decisões do usuário 25/09).
--
-- Funções novas em profiles.role (só enxergam CHAMADOS — nada do CRM de vendas):
--   secretaria  → vê os chamados das filas de que é membro (+ os atribuídos a ele)
--   tutor       → idem (ex.: tutor só de Pós é membro só da fila "Tutoria Pós")
--   coordenador → vê TODAS as filas
-- admin/agent continuam como antes (is_staff).
--
-- Filas: cada fila = nível (graduação/pós/todos) × assuntos (categorias) × membros.
-- Chamado novo cai na fila pelo gatilho: acadêmico → Tutoria do nível do aluno;
-- o resto → Secretaria (fila padrão, que também pega o que não casar com nada).
-- Nível do aluno: curso do chamado (courses.type) ou alunos.nivel (vem do Sponte).
-- ============================================================================

-- ── papéis ──────────────────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.my_role() RETURNS text
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT role FROM profiles WHERE id = auth.uid();
$$;
CREATE OR REPLACE FUNCTION public.is_ticket_staff() RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid()
                 AND role IN ('admin','agent','secretaria','tutor','coordenador'));
$$;

-- ── filas ───────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS ticket_queues (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome        text NOT NULL,
  nivel       text NOT NULL DEFAULT 'todos' CHECK (nivel IN ('todos','graduacao','pos')),
  categorias  ticket_categoria[] NOT NULL DEFAULT '{}',
  padrao      boolean NOT NULL DEFAULT false,   -- recebe o que não casar com nenhuma fila
  ativo       boolean NOT NULL DEFAULT true,
  ordem       integer NOT NULL DEFAULT 0,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS ticket_queue_members (
  queue_id    bigint NOT NULL REFERENCES ticket_queues(id) ON DELETE CASCADE,
  profile_id  uuid   NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  PRIMARY KEY (queue_id, profile_id)
);

INSERT INTO ticket_queues (nome, nivel, categorias, padrao, ordem)
SELECT * FROM (VALUES
  ('Secretaria', 'todos', '{secretaria,certificado,cancelamento,financeiro,suporte_tecnico,outros}'::ticket_categoria[], true, 1),
  ('Tutoria — Graduação', 'graduacao', '{academico}'::ticket_categoria[], false, 2),
  ('Tutoria — Pós-graduação', 'pos', '{academico}'::ticket_categoria[], false, 3)
) v(nome, nivel, categorias, padrao, ordem)
WHERE NOT EXISTS (SELECT 1 FROM ticket_queues);

ALTER TABLE tickets ADD COLUMN IF NOT EXISTS queue_id bigint REFERENCES ticket_queues(id) ON DELETE SET NULL;
ALTER TABLE tickets ADD COLUMN IF NOT EXISTS nivel text CHECK (nivel IN ('graduacao','pos'));
ALTER TABLE alunos  ADD COLUMN IF NOT EXISTS nivel text CHECK (nivel IN ('graduacao','pos'));
CREATE INDEX IF NOT EXISTS idx_tickets_queue ON tickets (queue_id);

-- ── visibilidade ────────────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.ticket_visible(p_queue bigint, p_atendente uuid) RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT CASE my_role()
    WHEN 'admin' THEN true
    WHEN 'agent' THEN true
    WHEN 'coordenador' THEN true
    WHEN 'secretaria' THEN p_atendente = auth.uid()
         OR EXISTS (SELECT 1 FROM ticket_queue_members m WHERE m.queue_id = p_queue AND m.profile_id = auth.uid())
    WHEN 'tutor' THEN p_atendente = auth.uid()
         OR EXISTS (SELECT 1 FROM ticket_queue_members m WHERE m.queue_id = p_queue AND m.profile_id = auth.uid())
    ELSE false END;
$$;

DROP POLICY IF EXISTS tickets_select ON tickets;
