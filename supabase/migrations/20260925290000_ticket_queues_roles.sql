  EXISTS (SELECT 1 FROM tickets t WHERE t.id = ticket_messages.ticket_id
          AND ((t.aluno_id = auth.uid() AND ticket_messages.interno = false)
               OR public.ticket_visible(t.queue_id, t.atendente_id))));

