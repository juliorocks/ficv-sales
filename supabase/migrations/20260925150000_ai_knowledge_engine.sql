-- ── estado da IA por lead (trava de handoff) ────────────────────────────────
CREATE TABLE IF NOT EXISTS ai_lead_sessions (
  lead_id         integer PRIMARY KEY REFERENCES leads(id) ON DELETE CASCADE,
  status          text NOT NULL DEFAULT 'active' CHECK (status IN ('active','handed_off','disabled')),
  ai_turns        integer NOT NULL DEFAULT 0,
  handoff_reason  text,
  handoff_summary text,
  handed_off_at   timestamptz,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE ai_lead_sessions ENABLE ROW LEVEL SECURITY;
CREATE POLICY ai_lead_sessions_sel ON ai_lead_sessions FOR SELECT USING (public.is_staff());
CREATE POLICY ai_lead_sessions_upd ON ai_lead_sessions FOR UPDATE USING (public.is_staff());

